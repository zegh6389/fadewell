import { test, expect } from '@playwright/test'

test('chat stays beside launcher and supports local messages, keyboard close, and reopening', async ({ page }) => {
  await page.goto('/')
  const launcher = page.getByRole('button', { name: 'Need help?' })
  await launcher.click()
  const dialog = page.getByRole('dialog', { name: 'MmjGreen care chat' })
  await expect(dialog).toBeVisible()
  const bounds = await dialog.boundingBox()
  const buttonBounds = await launcher.boundingBox()
  expect(Math.abs(bounds.x + bounds.width - buttonBounds.x - buttonBounds.width)).toBeLessThanOrEqual(1)
  expect(buttonBounds.y - bounds.y - bounds.height).toBeGreaterThan(0)
  expect(buttonBounds.y - bounds.y - bounds.height).toBeLessThan(64)
  expect(bounds.y).toBeGreaterThanOrEqual(0)

  const input = page.getByRole('textbox', { name: 'Your message' })
  const send = page.getByRole('button', { name: 'Send message' })
  await expect(input).toBeFocused()
  await expect(send).toBeDisabled()
  await input.fill('   ')
  await expect(send).toBeDisabled()
  await input.fill('How do I renew? <script>demo</script>')
  await input.press('Enter')
  await expect(page.getByRole('log')).toContainText('How do I renew? <script>demo</script>')
  await expect(page.getByRole('log')).toContainText('has not been sent to our team')
  await expect(input).toHaveValue('')
  await expect(send).toBeDisabled()
  await expect(input).toBeFocused()
  await input.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(launcher).toBeFocused()
  await launcher.click()
  await expect(page.getByRole('log')).toContainText('How do I renew?')
  await page.getByRole('button', { name: 'Close help' }).click()
  await expect(dialog).not.toBeVisible()
})
