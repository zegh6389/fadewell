const index = new Map(stateGuides.map((g) => [g.slug, g]))

/** Every resource in one list — articles first, then state guides. */
export const allResources = [...articles, ...stateGuides]

export function findResource(slug) {
  return allResources.find((item) => item.slug === slug) || null
}

export function isStateGuide(slug) {
  return index.has(slug)
}

/** Case-insensitive match on state name or postal code. */
export function searchStateGuides(query) {
  const q = query.trim().toLowerCase()
  if (!q) return stateGuides
  return stateGuides.filter(
    (g) => g.state.toLowerCase().includes(q) || g.code.toLowerCase() === q || g.program.toLowerCase().includes(q)
  )
}

